import { v4 as uuidv4 } from "uuid";
import {
  recommendParalegalTasks,
  parseAttorneyInstruction,
  type ParsedAttorneyInstruction,
} from "./openai";

export interface AiPipelineStorage {
  getCase: (caseId: string, userId: string) => Promise<any>;
  getWitnesses: (caseId: string) => Promise<any[]>;
  getEvidence: (caseId: string) => Promise<any[]>;
  getWeaknesses: (caseId: string) => Promise<any[]>;
  getDocuments: (caseId: string) => Promise<any[]>;
  createTask: (task: any) => Promise<any>;
}

export interface AiHelpers {
  recommendParalegalTasks: typeof recommendParalegalTasks;
  parseAttorneyInstruction: typeof parseAttorneyInstruction;
}

// Generate AI paralegal task recommendations for a case and insert them as
// status="recommended" caseTasks. Safe to call fire-and-forget after case upload
// or directly via the manual trigger endpoint. Returns the inserted task rows.
export async function generateRecommendationsForCase(
  caseId: string,
  userId: string,
  storage: AiPipelineStorage,
  helpers: AiHelpers = { recommendParalegalTasks, parseAttorneyInstruction },
): Promise<any[]> {
  const caseRec = await storage.getCase(caseId, userId);
  if (!caseRec) return [];

  const [witnesses, evidenceItems, weaknesses, documents] = await Promise.all([
    storage.getWitnesses(caseId).catch(() => []),
    storage.getEvidence(caseId).catch(() => []),
    storage.getWeaknesses(caseId).catch(() => []),
    storage.getDocuments(caseId).catch(() => []),
  ]);

  const recs = await helpers.recommendParalegalTasks({
    caseName: caseRec.name,
    defendant: caseRec.defendant,
    charges: caseRec.charges,
    parish: (caseRec as any).parish,
    arrestDate: (caseRec as any).arrestDate ? String((caseRec as any).arrestDate) : null,
    trialDate: (caseRec as any).trialDate ? String((caseRec as any).trialDate) : null,
    custodyStatus: (caseRec as any).custodyStatus,
    weaknesses: (weaknesses as any[]).map((w: any) => ({
      title: w.title || w.description || "Untitled",
      category: w.category,
      severity: w.severity,
    })),
    witnesses: (witnesses as any[]).map((w: any) => ({ name: w.name, role: w.role })),
    evidenceItems: (evidenceItems as any[]).map((e: any) => ({
      type: e.type || "evidence",
      description: e.description,
    })),
    documentTypes: Array.from(new Set((documents as any[]).map((d: any) => d.documentType).filter(Boolean))),
  });

  const inserted: any[] = [];
  for (const r of recs) {
    const dueDate = r.dueInDays != null
      ? new Date(Date.now() + r.dueInDays * 24 * 60 * 60 * 1000)
      : null;
    const row = await storage.createTask({
      id: uuidv4(),
      caseId,
      title: r.title,
      description: r.sourceReason ? `${r.description}\n\nWhy: ${r.sourceReason}` : r.description,
      stage: r.stage || null,
      priority: r.priority || "medium",
      status: "recommended",
      dueDate,
      sourceType: "ai_recommendation",
      sourceId: null,
      createdBy: userId,
      isAutoGenerated: true,
    });
    inserted.push(row);
  }
  return inserted;
}

// Fire-and-forget wrapper: never throws; logs and swallows errors so the calling
// HTTP response can return success even when OpenAI is slow, rate-limited, or
// returns malformed content.
export function generateRecommendationsForCaseSafe(
  caseId: string,
  userId: string,
  storage: AiPipelineStorage,
  helpers?: AiHelpers,
): Promise<any[] | null> {
  return generateRecommendationsForCase(caseId, userId, storage, helpers).catch((err) => {
    console.error(
      `Recommendation generation failed for case ${caseId}:`,
      err?.message || err,
    );
    return null;
  });
}

export interface AttorneyInstructionTaskResult {
  generatedTaskIds: string[];
  fallback: boolean;
}

// Convert an attorney's paralegal_instruction note into one or more structured
// tasks. If the AI call throws OR returns no tasks, falls back to a single
// pass-through task so the paralegal still sees the instruction.
export async function createTasksFromAttorneyInstruction(
  params: {
    noteId: string;
    caseId: string;
    userId: string;
    content: string;
    caseName?: string | null;
    caseContext?: string | null;
  },
  storage: Pick<AiPipelineStorage, "createTask">,
  helpers: { parseAttorneyInstruction: typeof parseAttorneyInstruction } = { parseAttorneyInstruction },
): Promise<AttorneyInstructionTaskResult> {
  const { noteId, caseId, userId, content } = params;
  let parsed: ParsedAttorneyInstruction | null = null;
  let aiFailed = false;

  try {
    parsed = await helpers.parseAttorneyInstruction({
      noteContent: content,
      caseName: params.caseName || null,
      caseContext: params.caseContext || null,
    });
  } catch (aiErr: any) {
    aiFailed = true;
    console.error(
      `AI parsing failed for note ${noteId}, falling back to simple task:`,
      aiErr?.message || aiErr,
    );
  }

  if (aiFailed || !parsed || parsed.tasks.length === 0) {
    const fallback = await storage.createTask({
      id: uuidv4(),
      caseId,
      title: `Attorney instruction: ${content.substring(0, 80)}`,
      description: content,
      sourceType: "attorney_note",
      sourceId: noteId,
      createdBy: userId,
      isAutoGenerated: true,
      status: "pending",
      priority: "medium",
    });
    return { generatedTaskIds: [fallback.id], fallback: true };
  }

  const createdIds: string[] = [];
  for (const t of parsed.tasks) {
    const dueDate = t.dueInDays != null
      ? new Date(Date.now() + t.dueInDays * 24 * 60 * 60 * 1000)
      : null;
    const created = await storage.createTask({
      id: uuidv4(),
      caseId,
      title: t.title,
      description: t.description,
      stage: t.stage || null,
      priority: t.priority || "medium",
      status: "recommended",
      dueDate,
      sourceType: "attorney_note",
      sourceId: noteId,
      createdBy: userId,
      isAutoGenerated: true,
    });
    createdIds.push(created.id);
  }
  return { generatedTaskIds: createdIds, fallback: false };
}
